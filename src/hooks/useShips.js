import { getShips } from "@/api/ships";
import { useQuery } from "@tanstack/react-query";

export function useShips({
  page = 1,
  page_size = 20,
  name,
  flag,
  vessel_class,
  vessel_maker,
  vessel_type,
  gallery_url,
  id,
  imo,
  imo_like,
  yob,
  dwt,
  yob_from,
  yob_to,
  loa_min,
  loa_max,
  width_min,
  width_max,
  draft_min,
  draft_max,
  dwt_min,
  dwt_max,
  create_time_from,
  create_time_to,
  update_time_from,
  update_time_to,
  sort_by = "id",
  sort_order = "desc",
} = {}) {
  const params = {
    page,
    page_size,
    name,
    flag,
    vessel_class,
    vessel_maker,
    vessel_type,
    gallery_url,
    id,
    imo,
    imo_like,
    yob,
    dwt,
    yob_from,
    yob_to,
    loa_min,
    loa_max,
    width_min,
    width_max,
    draft_min,
    draft_max,
    dwt_min,
    dwt_max,
    create_time_from,
    create_time_to,
    update_time_from,
    update_time_to,
    sort_by,
    sort_order,
  };

  return useQuery({
    queryKey: ["ships", params],
    queryFn: () => getShips(params),
  });
}
